"""Amendment 0.4 rule 6 / 0.5 rule 4: bring the 21 pilot extractions (pilot/extractions/, made 22 Nov by the
coordinating AI agent) into the full-review schema: extraction/json/<PMCID>.json. Values decided by the
coordinating agent on 23 Nov from the pilot notes and a re-read of data-source passages (provisional).
data_source: public re-use only where the paper analyses data generated by others (TCGA, GEO)."""
import json, glob
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
PUBLIC = {'PMC8085784': ('TCGA thyroid RNA-seq', [('E0006', 'Raw whole-transcriptome RNA-sequencing, Level 3 normalized mRNA expression read counts')]),
          'PMC13115908': ('GEO GSE53697 (Mount Sinai Brain Bank) via SRA', [('E0026', 'Raw paired-end RNA-seq data were obtained from the NCBI Sequence Read Archive (SRA)')])}
DIFF_ONLY = {'PMC6417675'}
for f in sorted(glob.glob(str(ROOT / 'pilot' / 'extractions' / '*.json'))):
    x = json.loads(open(f).read())
    p = x['pmcid']
    ds = PUBLIC.get(p)
    y = {'pmcid': p, 'tissue_category': x['tissue_category'], 'sub_site': '', 'year': x.get('year', ''), 'country': '',
         'eligible_fulltext': x['eligible_fulltext'], 'exclusion_reason': x.get('exclusion_reason', '') or ('not eligible on full text (pilot)' if not x['eligible_fulltext'] else ''),
         'data_source': {'value': 'public_reuse' if ds else 'own_samples', 'dataset': ds[0] if ds else '',
                         'evidence': [{'id': i, 'quote': q} for i, q in ds[1]] if ds else []},
         'method': x.get('method', {}), 'controls': x.get('controls', {}), 'decontamination': x.get('decontamination', {}),
         'biomass_qpcr': x.get('biomass_qpcr') or {'value': 'no', 'evidence': []},
         'n_target_samples': None,
         'list_type': '' if not x['eligible_fulltext'] else ('differential_only' if p in DIFF_ONLY else ('full_profile' if x.get('top5') else 'mixed')),
         'genera': x.get('genera', []), 'top5': x.get('top5', []),
         'figures_only': {'yes': 'yes', 'partial': 'partial'}.get(x.get('genera_in_figures_only', ''), 'no') if x['eligible_fulltext'] else '',
         'authors_conclusion': x.get('authors_conclusion', ''), 'notes': x.get('notes', ''),
         'extractor': 'AI agent (Claude Opus 5.5), pilot 2026-11-22; converted 2026-11-23', 'date': x.get('date', '2026-11-22')}
    if y['eligible_fulltext'] and not y['method']:
        y['method'] = {'value': 'other', 'evidence': []}
    (ROOT / 'extraction' / 'json' / f'{p}.json').write_text(json.dumps(y, indent=1, ensure_ascii=False))
print('converted')
